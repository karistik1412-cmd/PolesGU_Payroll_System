    // Локализация интерфейса.
    // Переводы хранятся в коде (а не в .resx), чтобы клиент оставался одним exe-файлом
    // без внешних ресурсов; отсутствующий ключ возвращается как есть — это безопасно.
    public static class Localization
    {
        private static AppLanguage _current = AppLanguage.Russian;

        public static AppLanguage Current
        {
            get { return _current; }
            set { _current = value; }
        }

        // Человекочитаемое название языка — всегда на самом языке
        public static string DisplayName(AppLanguage lang)
        {
            switch (lang)
            {
                case AppLanguage.English: return "English";
                case AppLanguage.Belarusian: return "Беларуская";
                default: return "Русский";
            }
        }

        public static string Code
        {
            get
            {
                switch (_current)
                {
                    case AppLanguage.English: return "en";
                    case AppLanguage.Belarusian: return "be";
                    default: return "ru";
                }
            }
        }

        // Стабильный код языка для сохранения на будущее (ключ в реестре)
        public static void SetByCode(string code)
        {
            if (string.IsNullOrEmpty(code)) return;
            switch (code.Trim().ToLowerInvariant())
            {
                case "en": _current = AppLanguage.English; break;
                case "be": _current = AppLanguage.Belarusian; break;
                default: _current = AppLanguage.Russian; break;
            }
        }

        // Перевод по ключу; форматирование — через string.Format при наличии аргументов
        public static string T(string key, params object[] args)
        {
            string text = Lookup(key);
            if (text == null) return key;
            return (args == null || args.Length == 0) ? text : string.Format(text, args);
        }

        private static string Lookup(string key)
        {
            if (string.IsNullOrEmpty(key)) return string.Empty;

            // Роли: "role.Администратор" -> "Администратор" / "Administrator" / "Адміністратар"
            if (key.StartsWith("role.", StringComparison.Ordinal))
                return RoleText(key.Substring(5));

            Dictionary<string, string> ru, en, be;
            if (!Ru.TryGetValue(key, out ru)) return null;
            Dictionary<string, string> table =
                _current == AppLanguage.English ? En :
                _current == AppLanguage.Belarusian ? Be : Ru;

            string value;
            if (table.TryGetValue(key, out value)) return value;
            return ru; // если перевод не задан — показываем русский, но не «сырой» ключ
        }

        public static string RoleText(string role)
        {
            if (string.IsNullOrEmpty(role)) return string.Empty;
            switch (_current)
            {
                case AppLanguage.English:
                    if (role == "Администратор") return "Administrator";
                    if (role == "Бухгалтер") return "Accountant";
                    if (role == "Экономист") return "Economist";
                    if (role == "Сотрудник") return "Employee";
                    break;
                case AppLanguage.Belarusian:
                    if (role == "Администратор") return "Адміністратар";
                    if (role == "Бухгалтер") return "Бухгалтар";
                    if (role == "Экономист") return "Эканаміст";
                    if (role == "Сотрудник") return "Супрацоўнік";
                    break;
            }
            return role;
        }

        // Обратное преобразование: подпись роли на текущем языке -> русский код роли
        public static string RoleFromText(string text)
        {
            if (string.IsNullOrEmpty(text)) return "Сотрудник";
            string t = text.Trim();
            if (t == "Администратор" || t == "Administrator" || t == "Адміністратар") return "Администратор";
            if (t == "Бухгалтер" || t == "Accountant" || t == "Бухгалтар") return "Бухгалтер";
            if (t == "Экономист" || t == "Economist" || t == "Эканаміст") return "Экономист";
            if (t == "Сотрудник" || t == "Employee" || t == "Супрацоўнік") return "Сотрудник";
            return t;
        }

        // Русский текст — ключ и значение одновременно (базовый язык интерфейса)
        private static Dictionary<string, string> Make(params string[] pairs)
        {
            var d = new Dictionary<string, string>(StringComparer.Ordinal);
            for (int i = 0; i + 1 < pairs.Length; i += 2)
                d[pairs[i]] = pairs[i + 1];
            return d;
        }

